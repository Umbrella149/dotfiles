-- ============================================================================
-- 全局选项  ——  全部是 Neovim 原生功能，不涉及任何插件
-- ============================================================================
-- 改这个文件是最安全的。每一项都可以在 nvim 里用 `:help '选项名'` 查文档，
-- 例如 `:help 'scrolloff'`。
-- 想临时试某个值，不用改文件，直接在 nvim 里敲 `:set scrolloff=10`。
-- ============================================================================

local o = vim.o

-- ---------------------------------------------------------------------------
-- 行号与光标
-- ---------------------------------------------------------------------------
o.number = true          -- 显示行号
o.relativenumber = true  -- 相对行号（方便 5j / 12k 这种跳转）
o.cursorline = true      -- 高亮当前行
o.scrolloff = 8          -- 光标上下至少留 8 行，不会贴到屏幕边
o.sidescrolloff = 8      -- 左右同理

-- ---------------------------------------------------------------------------
-- 缩进
-- ---------------------------------------------------------------------------
-- 注意：这是「全局默认值」。某些语言需要不同缩进时，改 after/ftplugin/ 下的文件，
-- 不要改这里。例如 after/ftplugin/c.lua 可以单独设 C 语言的缩进。
o.expandtab = true   -- Tab 键插入空格而不是制表符
o.shiftwidth = 2     -- 自动缩进（>> << 和自动缩进）的宽度
o.tabstop = 2        -- 一个制表符显示为几个空格宽
o.softtabstop = 2    -- 按 Tab/Backspace 时按几个空格计算
o.smartindent = true -- 根据语法自动缩进新行

-- ---------------------------------------------------------------------------
-- 搜索
-- ---------------------------------------------------------------------------
o.ignorecase = true      -- 搜索忽略大小写
o.smartcase = true       -- 但如果搜索词里有大写字母，就变回区分大小写
o.inccommand = 'split'   -- :%s/a/b 替换时实时预览（原生功能，很多人以为是插件）
o.hlsearch = true        -- 高亮所有匹配项（用 <Esc> 清除，见 keymaps.lua）

-- ---------------------------------------------------------------------------
-- 界面
-- ---------------------------------------------------------------------------
o.termguicolors = true   -- 启用 24 位真彩色，主题才能正常显示
o.signcolumn = 'yes'     -- 永远显示左侧标记栏（放诊断图标、git 标记），避免文字左右跳动
o.wrap = false           -- 不自动折行（长行横向滚动）
o.laststatus = 3         -- 全局状态栏：多个分屏只在最底部显示一条
o.showmode = false       -- 不显示 "-- INSERT --"，因为状态栏里已经有了
o.pumheight = 12         -- 补全弹窗最多显示 12 项
o.winborder = 'rounded'  -- 悬浮窗（K 看文档、重命名等）用圆角边框
o.splitright = true      -- 竖直分屏时新窗口在右边
o.splitbelow = true      -- 水平分屏时新窗口在下面

-- 补全弹窗的行为（原生补全用，见 lua/lsp/init.lua）
--   menuone   只有一个候选时也弹出来（否则会直接替换，容易误操作）
--   noselect  弹出时不自动选中第一项，要自己按 Tab 选
--   popup     旁边再开一个小窗显示这个候选的详细文档
--   fuzzy     模糊匹配（输入 fpr 能匹配到 fooPrint）
vim.opt.completeopt = { 'menu', 'menuone', 'noselect', 'popup', 'fuzzy' }

-- 显示不可见字符（空格/制表符等），排查缩进问题时很有用
o.list = true
vim.opt.listchars = { tab = '» ', trail = '·', nbsp = '␣' }

-- ---------------------------------------------------------------------------
-- 文件与撤销
-- ---------------------------------------------------------------------------
o.undofile = true        -- 持久化撤销：关掉 nvim 重新打开，还能继续 u 撤销
o.swapfile = false       -- 不生成 .swp 文件（有 undofile + git 就够了）
o.backup = false         -- 不生成备份文件
o.autoread = true        -- 文件被外部程序修改时自动重新读取
o.confirm = true         -- 退出时如果有未保存改动，弹窗询问而不是直接报错

-- ---------------------------------------------------------------------------
-- 交互
-- ---------------------------------------------------------------------------
o.mouse = 'a'                    -- 启用鼠标（调整分屏大小时很方便）
o.clipboard = 'unnamedplus'      -- y/p 直接用系统剪贴板（需要 wl-clipboard，已装）
o.updatetime = 200               -- 200ms 无操作后触发 CursorHold（诊断浮窗等）
o.timeoutlen = 400               -- 组合键等待时间。which-key 弹出的速度由它决定
o.splitkeep = 'screen'           -- 分屏时保持屏幕内容不跳动

-- ---------------------------------------------------------------------------
-- 折叠（用 treesitter 提供的语法折叠，但折叠功能本身是原生的）
-- ---------------------------------------------------------------------------
o.foldmethod = 'expr'
o.foldexpr = 'v:lua.vim.treesitter.foldexpr()'
o.foldlevel = 99      -- 打开文件时不折叠任何东西（要折叠时手动按 za）
o.foldtext = ''       -- 折叠行保留语法高亮

-- ---------------------------------------------------------------------------
-- 关掉一些用不到的内置插件，省一点启动时间
-- ---------------------------------------------------------------------------
vim.g.loaded_netrw = 1          -- 用 mini.files 代替 netrw 文件浏览
vim.g.loaded_netrwPlugin = 1
