-- ============================================================================
-- 键位（只放「不依赖插件」的）
-- ============================================================================
-- 重要约定：插件自己的键位写在 lua/plugins/<插件名>.lua 里，不写在这。
-- 这样你看到一个键位不认识，先在这里找；找不到就是某个插件的，去 plugins/ 找。
--
-- 查一个键现在绑到了什么：`:map <键>`，例如 `:map <leader>ff`
-- 查所有键位：按 <leader>sk（fzf-lua 提供）
-- ============================================================================

local map = vim.keymap.set

-- ---------------------------------------------------------------------------
-- 基础
-- ---------------------------------------------------------------------------
map('i', 'jk', '<Esc>', { desc = '回到 normal 模式' })

-- <Esc> 清除搜索高亮（搜完东西满屏黄色时按它）
-- map('n', '<Esc>', '<cmd>nohlsearch<cr>', { desc = '清除搜索高亮' })

-- Ctrl-S 保存（很多编辑器的肌肉记忆）
-- map({ 'n', 'i', 'v' }, '<C-s>', '<cmd>write<cr><Esc>', { desc = '保存' })

-- ---------------------------------------------------------------------------
-- 窗口（分屏）
-- ---------------------------------------------------------------------------
map('n', '<C-h>', '<C-w>h', { desc = '切到左边窗口' })
map('n', '<C-j>', '<C-w>j', { desc = '切到下面窗口' })
map('n', '<C-k>', '<C-w>k', { desc = '切到上面窗口' })
map('n', '<C-l>', '<C-w>l', { desc = '切到右边窗口' })

map('n', '<leader>ws', '<C-w>s', { desc = '水平分屏' })
map('n', '<leader>wv', '<C-w>v', { desc = '竖直分屏' })
map('n', '<leader>wd', '<C-w>c', { desc = '关闭当前窗口' })

-- 调整窗口大小（方向键）
map('n', '<C-Up>', '<cmd>resize +2<cr>', { desc = '窗口变高' })
map('n', '<C-Down>', '<cmd>resize -2<cr>', { desc = '窗口变矮' })
map('n', '<C-Left>', '<cmd>vertical resize -2<cr>', { desc = '窗口变窄' })
map('n', '<C-Right>', '<cmd>vertical resize +2<cr>', { desc = '窗口变宽' })

-- ---------------------------------------------------------------------------
-- Buffer（已打开的文件）
-- ---------------------------------------------------------------------------
-- 注：<leader><leader> 在打开的 buffer 间切换，定义在 plugins/fzf.lua（需要插件）
map('n', '<S-h>', '<cmd>bprevious<cr>', { desc = '上一个 buffer' })
map('n', '<S-l>', '<cmd>bnext<cr>', { desc = '下一个 buffer' })
map('n', '<leader>bd', '<cmd>bdelete<cr>', { desc = '关闭当前 buffer' })
map('n', '<leader>bo', '<cmd>%bdelete|edit#|bdelete#<cr>', { desc = '关闭其他所有 buffer' })

-- ---------------------------------------------------------------------------
-- 编辑体验的小优化
-- ---------------------------------------------------------------------------
-- visual 模式下 J/K 移动选中的行（会自动重新缩进）
map('v', 'J', ":m '>+1<cr>gv=gv", { desc = '选中行下移' })
map('v', 'K', ":m '<-2<cr>gv=gv", { desc = '选中行上移' })

-- visual 模式下 < > 缩进后保持选中，可以连续按
map('v', '<', '<gv', { desc = '减少缩进（保持选中）' })
map('v', '>', '>gv', { desc = '增加缩进（保持选中）' })

-- 搜索跳转后把结果居中，眼睛不用到处找
map('n', 'n', 'nzzzv', { desc = '下一个搜索结果（居中）' })
map('n', 'N', 'Nzzzv', { desc = '上一个搜索结果（居中）' })
map('n', '<C-d>', '<C-d>zz', { desc = '下翻半页（居中）' })
map('n', '<C-u>', '<C-u>zz', { desc = '上翻半页（居中）' })

-- ---------------------------------------------------------------------------
-- 退出
-- ---------------------------------------------------------------------------
map('n', '<leader>qq', '<cmd>quitall<cr>', { desc = '退出 Neovim' })

-- ---------------------------------------------------------------------------
-- 终端
-- ---------------------------------------------------------------------------
-- Neovim 自带终端（:terminal）。在终端里按 <Esc><Esc> 回到 normal 模式，
-- 否则 <Esc> 会被传给终端里的程序。
map('t', '<Esc><Esc>', '<C-\\><C-n>', { desc = '终端：回到 normal 模式' })

-- <leader>gg 打开 lazygit（用原生 :terminal，不需要插件）
map('n', '<leader>gg', function()
  -- 开一个新标签页跑 lazygit，退出后自动关掉标签页
  vim.cmd('tabnew')
  vim.cmd('terminal lazygit')
  vim.cmd('startinsert')
  vim.api.nvim_create_autocmd('TermClose', {
    buffer = 0,
    once = true,
    callback = function() pcall(vim.cmd, 'tabclose') end,
  })
end, { desc = 'lazygit' })
