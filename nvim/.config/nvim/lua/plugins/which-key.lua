-- ============================================================================
-- which-key —— 按下 <leader> 后弹出可用按键提示
-- ============================================================================
-- 按下 <Space> 停顿一下，屏幕下方会列出所有以 <Space> 开头的键位。
-- 弹出速度由下面的 delay 控制（毫秒）。
--
-- 提示里显示的说明文字，来自各个 keymap 定义时写的 desc = '...'。
-- 所以以后加键位时记得写 desc，否则这里会显示成一串看不懂的命令。
--
-- 官方文档：https://github.com/folke/which-key.nvim
-- 想看全部键位（不只是 leader 开头的）：<leader>sk
-- ============================================================================

local wk = require('which-key')

wk.setup({
  preset = 'helix',   -- 外观预设。可选 'classic'（底部横排）/ 'modern' / 'helix'（右侧竖排）
  delay = 300,        -- 按下 leader 后等多久弹出
  icons = {
    mappings = false, -- 不显示图标（需要 nerd font 且容易花屏），只显示文字
  },
})

-- ---------------------------------------------------------------------------
-- 给各个前缀起个组名，弹窗里就会显示「+文件」而不是一串键
-- ---------------------------------------------------------------------------
wk.add({
  { '<leader>f', group = '文件' },
  { '<leader>s', group = '搜索' },
  { '<leader>g', group = 'git' },
  { '<leader>b', group = 'buffer' },
  { '<leader>c', group = '代码' },
  { '<leader>w', group = '窗口' },
  { '<leader>q', group = '退出' },
  { '<leader>u', group = '开关' },
  { ']',         group = '下一个…' },
  { '[',         group = '上一个…' },
})
