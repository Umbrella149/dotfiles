-- ============================================================================
-- Neovim 配置入口
-- ============================================================================
-- 加载顺序是有讲究的，不要随意调换：
--   1. leader 键必须在任何键位定义之前设置，否则 <leader> 会绑到旧值
--   2. core 层不依赖任何插件，先加载
--   3. plugins 层负责下载/加载插件
--   4. lsp 层依赖 core 的诊断设置
--
-- 想知道每一层是干什么的，看 docs/ 目录。
-- ============================================================================

-- leader 键 = 空格。必须在最前面。
vim.g.mapleader = ' '
vim.g.maplocalleader = ' '

-- ---------------------------------------------------------------------------
-- 第一层：原生配置（零插件依赖）
-- 把 lua/plugins/ 整个删掉，下面这些依然完整可用。
-- ---------------------------------------------------------------------------
require('core.options')     -- 选项：行号、缩进、搜索……
require('core.keymaps')     -- 与插件无关的键位
require('core.autocmds')    -- 自动命令
require('core.treesitter')  -- treesitter 语法高亮（原生，不是插件）
require('core.diagnostic')  -- 诊断（报错/警告）的外观
require('core.statusline')  -- 手写状态栏

-- ---------------------------------------------------------------------------
-- 第二层：插件
-- ---------------------------------------------------------------------------
require('plugins')

-- ---------------------------------------------------------------------------
-- 第三层：LSP（代码补全/跳转/诊断）
-- ---------------------------------------------------------------------------
require('lsp')
